import yfinance as yf
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from scipy import stats
import warnings
warnings.filterwarnings('ignore')


class PortfolioAnalyzer:
    """
    Automated Portfolio Risk & Performance Analyzer

    Parameters
    ----------
    tickers : list
        List of stock tickers, e.g. ['AAPL', 'MSFT', 'JPM']
    weights : list
        Portfolio weights, corresponding to tickers, summing to 1
    benchmark : str
        Benchmark index ticker, default '^GSPC' (S&P 500)
    start_date : str
        Data start date, e.g. '2022-01-01'
    end_date : str
        Data end date, default None (until today)
    risk_free_rate : float
        Annualized risk-free rate, default 0.04 (4%)
    confidence_level : float
        VaR confidence level, default 0.95
    """

    def __init__(self, tickers, weights, benchmark='^GSPC',
                 start_date='2022-01-01', end_date=None,
                 risk_free_rate=0.04, confidence_level=0.95):

        # Validate weights
        if abs(sum(weights) - 1.0) > 1e-6:
            raise ValueError(f"Weights sum to {sum(weights)}, must equal 1")

        self.tickers = tickers
        self.weights = np.array(weights)
        self.benchmark = benchmark
        self.start_date = start_date
        self.end_date = end_date
        self.rf = risk_free_rate
        self.confidence = confidence_level

        self.data = None
        self.returns = None
        self.portfolio_returns = None
        self.metrics = {}

    def fetch_data(self):
        """Fetch adjusted closing prices for all assets and benchmark"""
        all_tickers = self.tickers + [self.benchmark]
        raw = yf.download(all_tickers, start=self.start_date,
                          end=self.end_date, auto_adjust=True, progress=False)

        # Handle yfinance multi-index column format
        if isinstance(raw.columns, pd.MultiIndex):
            prices = raw['Close'][all_tickers]
        else:
            prices = raw[all_tickers]

        # Drop rows with any NaN (ensures all assets have aligned dates)
        prices = prices.dropna()
        self.data = prices
        return self

    def calculate_returns(self):
        """Calculate daily simple returns"""
        prices = self.data
        self.returns = prices.pct_change().dropna()

        # Portfolio daily returns = weighted sum of individual asset returns
        self.portfolio_returns = (self.returns[self.tickers] * self.weights).sum(axis=1)
        return self

    def compute_metrics(self):
        """Calculate all risk and performance metrics"""
        pr = self.portfolio_returns
        bench_ret = self.returns[self.benchmark]
        n_days = len(pr)

        # --- Return metrics ---
        total_return = (1 + pr).prod() - 1
        annual_return = (1 + total_return) ** (252 / n_days) - 1

        # --- Risk metrics ---
        annual_vol = pr.std() * np.sqrt(252)

        # Sharpe ratio (annualized)
        excess_daily = pr.mean() - self.rf / 252
        sharpe = (excess_daily / pr.std()) * np.sqrt(252) if pr.std() > 0 else 0

        # Maximum drawdown
        cumulative = (1 + pr).cumprod()
        rolling_max = cumulative.cummax()
        drawdown = (cumulative - rolling_max) / rolling_max
        max_drawdown = drawdown.min()

        # Beta & Alpha (via regression against benchmark)
        bench_var = bench_ret.var()
        beta = pr.cov(bench_ret) / bench_var if bench_var > 0 else 0
        alpha_daily = pr.mean() - (self.rf/252 + beta * (bench_ret.mean() - self.rf/252))
        alpha_annual = alpha_daily * 252

        # VaR (Historical Simulation, 1-day)
        var_95 = np.percentile(pr, (1 - self.confidence) * 100)
        cvar_95 = pr[pr <= var_95].mean()  # Expected Shortfall

        self.metrics = {
            'Total Return': f"{total_return:.2%}",
            'Annualized Return': f"{annual_return:.2%}",
            'Annualized Volatility': f"{annual_vol:.2%}",
            'Sharpe Ratio': f"{sharpe:.2f}",
            'Max Drawdown': f"{max_drawdown:.2%}",
            'Beta (vs Benchmark)': f"{beta:.2f}",
            'Alpha (Annualized)': f"{alpha_annual:.2%}",
            f'VaR ({self.confidence:.0%}, 1-Day)': f"{var_95:.2%}",
            f'CVaR ({self.confidence:.0%}, 1-Day)': f"{cvar_95:.2%}",
            'Trading Days': n_days
        }

        # Store raw values for plotting
        self._raw = {
            'cumulative': cumulative,
            'drawdown': drawdown,
            'beta': beta,
            'var_95': var_95
        }
        return self

    def generate_report(self):
        """Print text report"""
        print("=" * 60)
        print("   PORTFOLIO RISK & PERFORMANCE REPORT")
        print("=" * 60)
        print(f"\nPortfolio: {dict(zip(self.tickers, self.weights))}")
        print(f"Benchmark: {self.benchmark}")
        print(f"Period: {self.data.index[0].date()} to {self.data.index[-1].date()}")
        print(f"Risk-Free Rate: {self.rf:.2%} | VaR Confidence: {self.confidence:.0%}")
        print("\n" + "-" * 60)
        print("   KEY METRICS")
        print("-" * 60)
        for k, v in self.metrics.items():
            print(f"  {k:<30} {v}")

        print("\n" + "-" * 60)
        print("   INTERPRETATION")
        print("-" * 60)
        beta = self._raw['beta']
        if beta > 1.1:
            beta_interp = f"Portfolio is MORE volatile than the market (Beta={beta:.2f}). Expected to amplify market movements."
        elif beta < 0.9:
            beta_interp = f"Portfolio is LESS volatile than the market (Beta={beta:.2f}). More defensive in nature."
        else:
            beta_interp = f"Portfolio moves roughly in line with the market (Beta={beta:.2f})."

        print(f"  • {beta_interp}")
        print(f"  • 95% VaR: On a typical bad day, the portfolio is expected to lose no more than "
              f"{abs(float(self.metrics['VaR (95%, 1-Day)'].strip('%'))):.2f}%.")
        print(f"  • Max Drawdown: The worst peak-to-trough loss was {self.metrics['Max Drawdown']}.")
        print(f"  • Sharpe Ratio {self.metrics['Sharpe Ratio']}: "
              f"{'Good risk-adjusted return' if float(self.metrics['Sharpe Ratio']) > 1 else 'Moderate risk-adjusted return'}.")
        print("=" * 60)

        return self

    def plot_results(self):
        """Generate 4-panel visualization"""
        fig, axes = plt.subplots(2, 2, figsize=(14, 10))

        # Panel 1: Cumulative returns - Portfolio vs Benchmark
        ax1 = axes[0, 0]
        bench_cum = (1 + self.returns[self.benchmark]).cumprod()
        ax1.plot(self._raw['cumulative'].index, self._raw['cumulative'].values,
                 label='Portfolio', linewidth=2)
        ax1.plot(bench_cum.index, bench_cum.values,
                 label='Benchmark', linewidth=1.5, alpha=0.8)
        ax1.set_title('Cumulative Growth of $1', fontsize=12, fontweight='bold')
        ax1.legend()
        ax1.grid(True, alpha=0.3)

        # Panel 2: Drawdown
        ax2 = axes[0, 1]
        ax2.fill_between(self._raw['drawdown'].index,
                         self._raw['drawdown'].values, 0,
                         color='red', alpha=0.4)
        ax2.plot(self._raw['drawdown'].index, self._raw['drawdown'].values,
                 color='darkred', linewidth=1)
        ax2.set_title('Drawdown from Peak', fontsize=12, fontweight='bold')
        ax2.set_ylabel('Drawdown %')
        ax2.grid(True, alpha=0.3)

        # Panel 3: Return distribution with VaR line
        ax3 = axes[1, 0]
        ax3.hist(self.portfolio_returns, bins=50, edgecolor='black', alpha=0.7, density=True)
        var_line = self._raw['var_95']
        ax3.axvline(var_line, color='red', linestyle='--', linewidth=2,
                    label=f'VaR ({self.confidence:.0%}) = {var_line:.2%}')
        ax3.set_title('Daily Return Distribution', fontsize=12, fontweight='bold')
        ax3.legend()
        ax3.grid(True, alpha=0.3)

        # Panel 4: Rolling volatility (30-day)
        ax4 = axes[1, 1]
        rolling_vol = self.portfolio_returns.rolling(30).std() * np.sqrt(252)
        ax4.plot(rolling_vol.index, rolling_vol.values, color='orange', linewidth=1.5)
        ax4.set_title('30-Day Rolling Annualized Volatility', fontsize=12, fontweight='bold')
        ax4.set_ylabel('Annualized Vol %')
        ax4.grid(True, alpha=0.3)

        plt.tight_layout()
        plt.savefig('portfolio_analysis.png', dpi=150, bbox_inches='tight')
        print("\n✅ Chart saved: portfolio_analysis.png")
        plt.show()


